#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════
// RIKIKI · scene bench, the capacity table
//
//   node scripts/scene-bench/capacity.mjs [--widths 1600,1000,752,469] [--out capacity.json]
//
// How many characters of plain text each field of each shape takes, at a width
// and at its fewest, middle and most items, on the real fonts · found by
// halving. This is the number behind "a note is one short sentence": measured,
// not guessed, so the skill can say how short.
// ════════════════════════════════════════════════════════════════

import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { openBench } from './runner.mjs';

const { values } = parseArgs({
  options: {
    widths: { type: 'string', default: '1600,1250,1000,850,752,650,560,469' },
    out: { type: 'string' },
    ts: { type: 'string' },
    port: { type: 'string', default: '7815' },
  },
});

const bench = await openBench(Number(values.port));
try {
  const widths = values.widths.split(',').map(Number);
  const table = await bench.page.evaluate((w) => window.bench.capacityTable(w), widths);
  const result = { measuredWith: 'plain words of 6 letters, identical items', widths, table };
  if (values.out) writeFileSync(values.out, `${JSON.stringify(result, null, 2)}\n`);
  if (values.ts) {
    const header = `// ════════════════════════════════════════════════════════════════
// GENERATED by scripts/scene-bench/capacity.mjs · do not edit by hand.
//
// How many characters of plain text each field of each scene takes, by canvas
// width and item count, measured on the real fonts (identical items, words of six
// letters) · \`capacityOf\` in scene-capacity.ts reads it. Regenerate with
//   node scripts/scene-bench/capacity.mjs --ts src/media/scene-capacity.data.ts
// ════════════════════════════════════════════════════════════════

`;
    const body = `export const CAPACITY_WIDTHS = ${JSON.stringify(widths)} as const;\n\nexport const SCENE_CAPACITY: Readonly<Record<string, Readonly<Record<number, Readonly<Record<number, Readonly<Record<string, number>>>>>>>> = ${JSON.stringify(table, null, 2)};\n`;
    writeFileSync(values.ts, header + body);
  }
  for (const [kind, byWidth] of Object.entries(table)) {
    console.log(kind);
    for (const [width, byCount] of Object.entries(byWidth)) {
      const cells = Object.entries(byCount)
        .map(
          ([count, fields]) =>
            `${count}: ${Object.entries(fields)
              .map(([f, n]) => `${f} ${n}`)
              .join(', ')}`,
        )
        .join('  |  ');
      console.log(`  ${width.padStart(5)} · ${cells}`);
    }
  }
} finally {
  await bench.close();
}
